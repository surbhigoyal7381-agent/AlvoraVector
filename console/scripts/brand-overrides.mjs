#!/usr/bin/env node
// Generates console/translations/brand-overrides/<locale>.yaml for every host locale.
//
// Why: Fleetbase engines (fleetops, iam, dev, storefront ...) ship their own translations that say
// "Fleetbase". ember-intl lets the host app win over engines, so for every engine value that names
// Fleetbase we write the same key here with "Alvora Vector". Nothing under node_modules is edited.
//
// Usage (Node 22, from console/):   node scripts/brand-overrides.mjs
// Re-run after every `pnpm install` that changes an @fleetbase package (each upstream upgrade),
// then commit the changed files. `pnpm lint:brand` fails when they are stale.
// Hand-written host strings live in translations/<locale>.yaml and are never touched by this script;
// a key the host already defines is skipped so host text always wins.
import fs from 'node:fs';
import path from 'node:path';
import { allLocales, engineTranslations, flatten, hostFile, nest, overridesDir, readYaml, rebrand, yaml } from './brand-rules.mjs';

const HEADER = '# GENERATED by scripts/brand-overrides.mjs. Do not edit; re-run the script after upstream upgrades.\n';
const engines = engineTranslations();
fs.rmSync(overridesDir, { recursive: true, force: true });
fs.mkdirSync(overridesDir, { recursive: true });

let total = 0;
for (const locale of allLocales()) {
    const hostPath = hostFile(locale);
    const host = hostPath ? flatten(readYaml(hostPath)) : {};
    const out = {};
    for (const { flat } of engines[locale] || []) {
        for (const [key, value] of Object.entries(flat)) {
            const next = key in host ? null : rebrand(key, value);
            if (next !== null) out[key] = next;
        }
    }
    const keys = Object.keys(out).sort();
    if (keys.length) {
        fs.writeFileSync(path.join(overridesDir, `${locale}.yaml`), HEADER + yaml.dump(nest(Object.fromEntries(keys.map((k) => [k, out[k]]))), { lineWidth: -1 }));
    }
    total += keys.length;
    console.log(`${locale}: ${keys.length} overrides`);
}
console.log(`total: ${total}`);
